#!/bin/sh
# ส่วนที่สคริปต์ sync ทุกตัวใช้ร่วมกัน — รันข้างใน container ของ api (ไม่ใช่บนโฮสต์)
#
# ทำไมไม่เขียนล็อกลงไฟล์เหมือนฝั่ง .ps1:
#   ใน Docker ของที่พิมพ์ออก stdout จะถูกเก็บโดย docker logs อยู่แล้ว ถ้ามาเขียนไฟล์เองอีก
#   จะได้ล็อกสองที่ที่ไม่ตรงกัน และไฟล์จะโตอยู่ในดิสก์ของ container ที่หายตอน build ใหม่
#   ฝั่ง cron บนโฮสต์เป็นคนเก็บลงไฟล์ + ลบของเก่า (ดู deploy/cron/)

PYTHONIOENCODING=utf-8
export PYTHONIOENCODING

FAILED=""

say() {
  echo "$(date '+%Y-%m-%d %H:%M:%S') $*"
}

# run <ชื่อที่จะโชว์> <คำสั่ง...>
# ตัวไหนล้มก็จดไว้แล้วไปต่อ — ขั้นตอนส่วนใหญ่ไม่ได้ขึ้นต่อกัน การหยุดทั้งชุดเพราะตัวเดียวพัง
# แปลว่าของที่เหลือไม่ได้อัปเดตทั้งที่มันทำได้ · สรุปรวมตอนจบแล้วค่อย exit 1
run() {
  label="$1"
  shift
  say "=== $label ==="
  # ต้องเก็บ $? ทันทีหลังคำสั่ง — ถ้าไปอ่านหลัง "fi" จะได้สถานะของตัว if ไม่ใช่ของคำสั่ง
  # (เจอตอนทดสอบ: ขั้นที่ล้มด้วย exit 3 รายงานออกมาเป็น exit 0 ซึ่งตามหาสาเหตุไม่ได้เลย)
  "$@"
  code=$?
  if [ "$code" -eq 0 ]; then
    return 0
  fi
  say "! $label ล้มเหลว (exit $code)"
  FAILED="$FAILED $label"
  return 1
}

finish() {
  what="$1"
  if [ -n "$FAILED" ]; then
    say "$what เสร็จแบบมีปัญหา — ที่ล้ม:$FAILED"
    say "ดูล็อกของขั้นนั้น แล้วรันเฉพาะตัวที่ล้มซ้ำได้เลย ไม่ต้องเริ่มใหม่ทั้งชุด"
    exit 1
  fi
  say "$what เสร็จเรียบร้อย"
}
